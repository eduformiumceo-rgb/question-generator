/**
 * Writes src/curriculumManifest.js: for every subject, which classes it has data for.
 * The subject picker and SHS course list need this for ALL subjects instantly, without
 * downloading any curriculum data. tests/curriculumLazy.test.js fails if this file is stale.
 *
 *   npm run sync:curriculum
 */
import fs from "fs";
import { LOADERS } from "../src/curriculumLoaders.js";

const manifest = {};
for (const [name, load] of Object.entries(LOADERS)) manifest[name] = Object.keys(await load());
const header = "// GENERATED by scripts/gen-curriculum-manifest.mjs (npm run sync:curriculum). Do not edit by hand.\n// Subject -> the classes it has curriculum data for. Lets the app answer \"which subjects exist for this class?\" without downloading any data.\nexport default ";
fs.writeFileSync(new URL("../src/curriculumManifest.js", import.meta.url), header + JSON.stringify(manifest, null, 1) + ";\n");
console.log(`curriculumManifest.js: ${Object.keys(manifest).length} subjects`);
